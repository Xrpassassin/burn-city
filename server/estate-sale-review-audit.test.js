'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateLatePaymentReconciliation}=require('./estate-sale-late-reconciliation');
const {createEstateReviewAudit}=require('./estate-sale-review-audit');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY)');
createEstateLatePaymentReconciliation(db);
const admin='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',stranger='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd';
db.prepare('INSERT INTO estate_late_payment_reviews(reservation_id,buyer,tx_hash,observed_at) VALUES(?,?,?,?)').run('reservation-00000001',stranger,'A'.repeat(64),10000);
const audit=createEstateReviewAudit(db,{adminAccounts:[admin]});
assert.equal(audit.record({actor:stranger,reservationId:'reservation-00000001',decision:'investigate',rationale:'Check on ledger evidence'}).error,'admin_not_authorized');
assert.equal(audit.record({actor:admin,reservationId:'reservation-00000001',decision:'refund_issued',rationale:'This must not issue funds'}).error,'invalid_decision');
assert.equal(audit.record({actor:admin,reservationId:'reservation-00000001',decision:'investigate',rationale:'short'}).error,'invalid_rationale');
const recorded=audit.record({actor:admin,reservationId:'reservation-00000001',decision:'refund_recommended',rationale:'Payment validated; verify refund eligibility'});
assert.equal(recorded.ok,true);assert.equal(recorded.actionExecuted,false);
assert.equal(audit.history({actor:admin,reservationId:'reservation-00000001'}).events.length,1);
assert.equal(audit.history({actor:stranger,reservationId:'reservation-00000001'}).error,'admin_not_authorized');
assert.equal(db.prepare("SELECT status FROM estate_late_payment_reviews WHERE reservation_id='reservation-00000001'").get().status,'needs_review');
console.log('Estate admin review audit tests passed');

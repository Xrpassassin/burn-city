'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateImgOwnershipSnapshots,createOwnedImgRewardAllocator}=require('./estate-img-ownership-snapshots');
const {createVerifiedImgRewardIngestion}=require('./estate-img-verified-ingestion');
const db=new DatabaseSync(':memory:');
const treasury='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',source='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd',hash='A'.repeat(64);
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,acct TEXT NOT NULL,purchase_tx TEXT NOT NULL UNIQUE,purchase_amount_drops INTEGER NOT NULL,share_units INTEGER NOT NULL,purchased_at INTEGER NOT NULL)');
const ins=db.prepare('INSERT INTO estate_property_ownership VALUES(?,?,?,?,?,?)');
ins.run('trailer-01',treasury,'B'.repeat(64),3000000,1,1000);
ins.run('trailer-02',source,'C'.repeat(64),3000000,1,2000);
const snapshots=createEstateImgOwnershipSnapshots(db);
assert.equal(snapshots.at(1500).length,1);
assert.equal(snapshots.at(2000).length,2);
assert.throws(()=>snapshots.at(-1),/invalid_receipt_timestamp/);
const receivedAtMs=(900000000+946684800)*1000;
const ingestion=createVerifiedImgRewardIngestion({db,treasury,imgIssuer:source,allowedSources:[source],client:{request:async()=>({result:{hash,validated:true,ledger_index:101,date:900000000,TransactionType:'Payment',Account:source,Destination:treasury,meta:{TransactionResult:'tesSUCCESS',delivered_amount:{currency:'IMG',issuer:source,value:'1'}}}})}});
(async()=>{
 await ingestion.ingest(hash);
 const later=receivedAtMs+1000;
 db.prepare('UPDATE estate_property_ownership SET purchased_at=? WHERE property_id=?').run(later,'trailer-02');
 const allocator=createOwnedImgRewardAllocator(db,ingestion);
 const result=allocator.allocate(hash);
 assert.equal(result.allocations.length,1);
 assert.equal(result.allocations[0].propertyId,'trailer-01');
 assert.equal(result.allocations[0].amountUnits,'1000000');
 assert.throws(()=>allocator.allocate(hash),/reward_already_allocated/);
 console.log('IMG receipt-time settled ownership snapshots passed');
})().catch(e=>{console.error(e);process.exitCode=1});

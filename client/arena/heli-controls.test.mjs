import assert from 'node:assert/strict';
import {helicopterAudioGain,helicopterGunnerControls} from './heli-controls.mjs';
const near=helicopterAudioGain(0,{volume:.3});
assert(near>0&&near<=.04,'rotor is much quieter than original standalone 55% helicopter volume');
assert.equal(helicopterAudioGain(0,{volume:0}),0,'game volume 0 must also mute rotor');
assert.equal(helicopterAudioGain(0,{volume:1,muted:true}),0,'game mute must also mute rotor');
assert.equal(helicopterAudioGain(1,{volume:1,visible:false}),0,'hidden or departed helicopter is silent');
assert.equal(helicopterAudioGain(200,{volume:1}),0,'distant rotor is inaudible');
assert(helicopterAudioGain(10,{volume:.3})>helicopterAudioGain(100,{volume:.3}));
assert(helicopterAudioGain(10,{volume:1})>helicopterAudioGain(10,{volume:.3}));
for(const d of [NaN,-Infinity,Infinity,-10])assert(Number.isFinite(helicopterAudioGain(d)));
const s=[2,45,[7],0,1,[0,0],[0,0],10,20,4,0];
assert.deepEqual(helicopterGunnerControls(null,7),{aboard:false,mounted:false,available:false,seat:-1,canInteract:false});
assert.equal(helicopterGunnerControls(s,7).canInteract,true,'boarding permits taking empty gun');
assert.equal(helicopterGunnerControls(s,8).canInteract,false,'other players cannot man gun remotely');
s[5][0]=7;
assert.equal(helicopterGunnerControls(s,7).mounted,true);
assert.equal(helicopterGunnerControls(s,7).seat,0);
assert.equal(helicopterGunnerControls(s,7).canInteract,true,'mounted gun has exit action');
s[5][1]=9;
assert.equal(helicopterGunnerControls(s,7).available,false);
assert.equal(helicopterGunnerControls(s,8).canInteract,false);
s[0]=3;
assert.equal(helicopterGunnerControls(s,7).mounted,true,'gunner remains usable during lift');
s[0]=4;
assert.equal(helicopterGunnerControls(s,7).canInteract,false,'no boarding stale wreck');
console.log('Original Zombies helicopter volume/mute, boarding, occupied seats, gunner use and map teardown state passed');

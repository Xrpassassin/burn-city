'use strict';
const assert=require('node:assert/strict'),{DatabaseSync}=require('node:sqlite');
const {createEstateTycoonStore}=require('./estate-tycoon');
const {ROOMS,privateRoomAccess,privateRoomOptions}=require('./estate-tycoon-rooms');
const owner='rKZmQq3gMCNmV6th3wZPhfqgZ3815vUmiV',guest='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb';
const db=new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON;CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,acct TEXT,purchase_tx TEXT UNIQUE,purchase_amount_drops INTEGER,share_units INTEGER,purchased_at INTEGER)');
db.prepare('INSERT INTO estate_property_ownership VALUES(?,?,?,?,?,?)').run('trailer-01',owner,'B'.repeat(64),3000000,1,1);
const store=createEstateTycoonStore(db);
const owners=(acct,propertyId)=>({allowed:acct===owner&&propertyId==='trailer-01',role:acct===owner?'owner':'visitor',permissions:acct===owner?['enter','inspect','build']:[],reason:'no_access'});
const guestAccess=(acct,propertyId)=>({allowed:propertyId==='trailer-01'&&(acct===owner||acct===guest),role:acct===owner?'owner':'guest',permissions:['enter','inspect']});
const args={propertyId:'trailer-01',acct:owner,accessFor:owners,tycoonStore:store};
assert.equal(ROOMS.length,6);
assert.equal(privateRoomOptions(args).ok,true);
assert.equal(privateRoomOptions(args).rooms.length,0);
assert.equal(privateRoomOptions({...args,acct:''}).error,'sign_in_with_xaman');
assert.equal(privateRoomOptions({...args,acct:guest}).error,'no_access');
assert.equal(privateRoomAccess({...args,roomId:'bunker'}).error,'room_not_unlocked');
assert.equal(privateRoomAccess({...args,roomId:'invalid'}).error,'unknown_private_room');
const access={...args,accessFor:guestAccess};
assert.equal(privateRoomOptions({...access,acct:guest}).rooms.length,0);
let seq=0;
function unlock(itemId){
 const orderId='tycoon_'+String(++seq).padStart(40,'a').replace(/[^a-f0-9]/g,'a');
 const row=store.reserve({propertyId:'trailer-01',buyer:owner,itemId,orderId,now:1800000000000+seq*1000});
 store.settle({orderId:row.order_id,buyer:owner,txHash:String(seq).padStart(64,'A'),ledgerIndex:100+seq,now:1800000000000+seq*1000+50});
}
unlock('reinforced-floor');
unlock('hidden-hatch');
assert.equal(privateRoomOptions(args).rooms.length,0,'A decorative hatch never opens unpurchased bunker space');
unlock('underground-bunker');
unlock('grow-lounge');
unlock('hobby-workshop');
const ownerRooms=privateRoomOptions(args);
assert.deepEqual(ownerRooms.rooms.map(r=>r.id),['bunker','lounge','workshop']);
assert.equal(privateRoomAccess({...args,roomId:'bunker'}).allowed,true);
assert.equal(privateRoomAccess({...access,acct:guest,roomId:'bunker'}).role,'guest');
assert.equal(privateRoomAccess({...args,roomId:'vault'}).error,'room_not_unlocked');
assert.equal(privateRoomAccess({...access,acct:guest,roomId:'arcade'}).error,'room_not_unlocked');
assert.equal(privateRoomOptions({...args,accessFor:()=>({allowed:true,role:'tour',permissions:['enter','inspect']})}).error,'no_access','public tours must never access secrets');
assert.equal(privateRoomOptions({...args,accessFor:()=>({allowed:false,role:'visitor',permissions:[],reason:'invite_revoked'})}).error,'invite_revoked');
assert.equal(privateRoomOptions({...args,propertyId:'trailer-02',accessFor:()=>({allowed:true,role:'owner',permissions:['enter']})}).error,'property_unowned');
assert(!JSON.stringify(ownerRooms).includes(owner),'API must not return owner wallet or payment hashes');
db.close();
console.log('Estates secret rooms: prerequisite gates, guest access, tour denial, revoked invitations and room privacy passed');

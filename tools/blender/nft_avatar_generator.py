"""Deterministic Blender background generator for BURN City NFT avatar build specs.

Creates an explicitly procedural BLOCKOUT candidate, not a faithful NFT reconstruction.
Requires Blender with bpy and glTF 2.0 exporter. Input JSON is generated by nft-avatar-build-spec.mjs.
"""
import bpy, json, math, os, sys, hashlib
from mathutils import Vector

def args_after_separator():
    return sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []

def material(name, color, metallic=0.0, roughness=0.65, emission=0.0):
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = (*color, 1.0)
    mat.use_nodes = True
    bsdf = mat.node_tree.nodes.get("Principled BSDF")
    bsdf.inputs["Base Color"].default_value = (*color, 1.0)
    bsdf.inputs["Metallic"].default_value = metallic
    bsdf.inputs["Roughness"].default_value = roughness
    if emission:
        bsdf.inputs["Emission Color"].default_value = (*color, 1.0)
        bsdf.inputs["Emission Strength"].default_value = emission
    return mat

def assign(obj, mat):
    obj.data.materials.append(mat)
    return obj

def uv_sphere(name, loc, scale, mat, segments=16, rings=12):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments, ring_count=rings, location=loc)
    obj = bpy.context.object
    obj.name = name
    obj.scale = scale
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    return assign(obj, mat)

def cube(name, loc, scale, mat, bevel=0.04):
    bpy.ops.mesh.primitive_cube_add(size=1, location=loc)
    obj = bpy.context.object
    obj.name = name
    obj.dimensions = scale
    bpy.ops.object.transform_apply(location=False, rotation=False, scale=True)
    if bevel:
        mod = obj.modifiers.new("Soft blockout edges", "BEVEL")
        mod.width = bevel
        mod.segments = 2
        obj.modifiers.new("Weighted normals", "WEIGHTED_NORMAL")
    return assign(obj, mat)

def cone(name, loc, radius1, radius2, depth, mat, rotation=(0,0,0), vertices=12):
    bpy.ops.mesh.primitive_cone_add(vertices=vertices, radius1=radius1, radius2=radius2, depth=depth, location=loc, rotation=rotation)
    return assign(bpy.context.object, mat)

def cylinder(name, loc, radius, depth, mat, rotation=(0,0,0), vertices=12):
    bpy.ops.mesh.primitive_cylinder_add(vertices=vertices, radius=radius, depth=depth, location=loc, rotation=rotation)
    return assign(bpy.context.object, mat)

def make_curve(name, points, mat, radius=0.065):
    curve = bpy.data.curves.new(name, "CURVE")
    curve.dimensions = "3D"
    curve.resolution_u = 2
    curve.bevel_depth = radius
    curve.bevel_resolution = 2
    spline = curve.splines.new("POLY")
    spline.points.add(len(points)-1)
    for p, co in zip(spline.points, points):
        p.co = (*co, 1.0)
    obj = bpy.data.objects.new(name, curve)
    bpy.context.collection.objects.link(obj)
    return assign(obj, mat)

def main():
    args = args_after_separator()
    if len(args) != 2:
        raise SystemExit("Usage: blender -b --python nft_avatar_generator.py -- build-spec.json output.glb")
    spec_path, output_path = map(os.path.abspath, args)
    with open(spec_path, "r", encoding="utf-8") as f:
        spec = json.load(f)
    if spec.get("specVersion") != 1 or not spec.get("reconstruction"):
        raise SystemExit("Unsupported or incomplete NFT avatar build spec")
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    bpy.ops.object.select_all(action="SELECT")
    bpy.ops.object.delete(use_global=False)
    for data in bpy.data.materials: bpy.data.materials.remove(data)
    key = spec["identity"]["collectionKey"]
    seed = sum(ord(ch) for ch in str(spec["identity"].get("tokenId", ""))) % 97
    if key == "racc":
        fur = material("RACC_Fur", (0.24,0.19,0.16)); light = material("RACC_Muzzle", (0.62,0.53,0.43))
        dark = material("RACC_Mask", (0.07,0.065,0.06)); outfit = material("RACC_Outfit", (0.20,0.28,0.34))
        accent = material("RACC_Tail_Ring", (0.80,0.74,0.61)); metal = material("RACC_Metal", (0.55,0.34,0.12),0.55)
    elif key == "fk":
        fur = material("Keeper_Skin", (0.43,0.35,0.31)); light = material("Keeper_Cloth_Light", (0.31,0.27,0.24))
        dark = material("Keeper_Shadow", (0.075,0.065,0.06)); outfit = material("Keeper_Robe", (0.16,0.13,0.12))
        accent = material("Keeper_Ember", (1.0,0.19,0.025),0.15,0.4,3.0); metal = material("Keeper_Relic", (0.85,0.48,0.08),0.65)
    elif key == "589":
        fur = material("Protocol_Skin", (0.57,0.40,0.32)); light = material("Protocol_Trim", (0.75,0.12,0.09))
        dark = material("Protocol_Shadow", (0.035,0.04,0.055)); outfit = material("Protocol_Streetwear", (0.10,0.12,0.16))
        accent = material("Protocol_BURN_Accent", (0.92,0.08,0.045),0.1,0.5,0.25); metal = material("Protocol_Chain", (0.62,0.65,0.68),0.8,0.28)
    else:
        fur = material("Fallback_Skin", (0.47,0.34,0.27)); light = material("Fallback_Trim", (0.55,0.47,0.37))
        dark = material("Fallback_Shadow", (0.08,0.08,0.08)); outfit = material("Fallback_Outfit", (0.18,0.22,0.27))
        accent = material("Fallback_Accent", (0.65,0.12,0.08)); metal = material("Fallback_Metal", (0.55,0.55,0.55),0.6)
    r = spec["reconstruction"]
    p = r.get("proportions", {})
    torso_w = float(p.get("torsoWidth",1.0)); torso_h=float(p.get("torsoHeight",1.0))
    head_scale=p.get("headScale",[1,1,1]); head_y=float(p.get("headY",1.75))
    # Facing -Y; all dimensions are approximate meters and form a readable blockout.
    uv_sphere("Body_Torso", (0,0,1.05), (0.32*torso_w,0.20,0.42*torso_h), outfit)
    uv_sphere("Body_Pelvis", (0,0,0.72), (0.25,0.17,0.20), dark)
    uv_sphere("Head_Base", (0,-0.015,head_y), (0.22*head_scale[0],0.20*head_scale[1],0.25*head_scale[2]), fur)
    uv_sphere("Face_Nose", (0,-0.195,head_y-0.055), (0.075,0.035,0.055), light)
    uv_sphere("Eye_L", (-0.085,-0.185,head_y+0.035), (0.035,0.025,0.035), dark,12,8)
    uv_sphere("Eye_R", (0.085,-0.185,head_y+0.035), (0.035,0.025,0.035), dark,12,8)
    # Arms and legs are separated named pieces so a later rigging stage can bind them.
    for side, label in [(-1,"L"),(1,"R")]:
        uv_sphere("Shoulder_"+label, (side*0.34,0,1.30), (0.12,0.13,0.14), outfit)
        cylinder("UpperArm_"+label, (side*0.39,0,1.08), 0.075, 0.32, outfit, rotation=(0,side*0.12,side*0.10))
        uv_sphere("Hand_"+label, (side*0.40,-0.01,0.89), (0.075,0.07,0.075), fur)
        cylinder("Leg_"+label, (side*0.13,0,0.40), 0.09, 0.48, dark)
        cube("Boot_"+label, (side*0.13,-0.055,0.12), (0.17,0.28,0.12), light,0.025)
    if key == "racc":
        # Eye-mask and muzzle establish the species read; ringed tail is signature geometry.
        uv_sphere("Raccoon_EyeMask", (0,-0.187,head_y+0.04), (0.205,0.035,0.075), dark)
        uv_sphere("Raccoon_Muzzle", (0,-0.222,head_y-0.075), (0.13,0.06,0.075), light)
        uv_sphere("Raccoon_Nose", (0,-0.275,head_y-0.045), (0.035,0.025,0.025), dark,12,8)
        tail_points=[(0.16,0.12,0.78),(0.36,0.20,0.69),(0.55,0.22,0.76),(0.70,0.20,0.91),(0.75,0.18,1.06)]
        make_curve("Raccoon_Ringed_Tail",tail_points,fur,0.095)
        for i, pt in enumerate(tail_points[1:-1]):
            uv_sphere("Tail_Ring_%02d"%i,pt,(0.09,0.09,0.09),accent if i%2==0 else dark,12,8)
        cone("Raccoon_Ear_L",(-0.15,0,head_y+0.22),0.075,0.012,0.16,fur)
        cone("Raccoon_Ear_R",(0.15,0,head_y+0.22),0.075,0.012,0.16,fur)
    elif key == "fk":
        # Layered robe blockout; cloth folds and exact source motifs remain authoring tasks.
        cone("Robe_Outer_Hem",(0,0,0.76),0.39,0.23,0.72,outfit)
        cone("Robe_Inner_Layer",(0,-0.015,0.83),0.32,0.21,0.65,light)
        uv_sphere("Cowl", (0,0,head_y-0.14), (0.29,0.24,0.22), dark)
        uv_sphere("Ember_Sigil",(0,-0.218,1.13),(0.065,0.025,0.085),accent,12,8)
        for side in (-1,1):
            uv_sphere("Shoulder_Ember", (side*0.30,-0.02,1.31), (0.05,0.05,0.05), accent,12,8)
    elif key == "589":
        cube("Protocol_Chest_Panel",(0,-0.205,1.13),(0.22,0.025,0.20),dark,0.015)
        # Simple BURN mark is geometry, not a copied logo or text glyph.
        cube("BURN_Mark_Vertical",(0,-0.226,1.13),(0.025,0.012,0.12),accent,0.004)
        cube("BURN_Mark_Crossbar",(0,-0.228,1.13),(0.10,0.012,0.025),accent,0.004)
        make_curve("Protocol_Chain",[(-0.12,-0.24,1.34),(-0.10,-0.255,1.18),(0,-0.26,1.10),(0.10,-0.255,1.18),(0.12,-0.24,1.34)],metal,0.012)
        cube("Streetwear_Collar",(0,-0.02,1.42),(0.26,0.22,0.09),dark,0.02)
    # Per-token trait pass: collection archetype establishes the silhouette; individual NFT
    # traits then alter visible materials and add token-specific geometry. This is still a
    # procedural blockout and must pass human likeness/rights QA before runtime approval.
    trait_rows = spec.get("traits", {}).get("normalized", [])
    trait_map = {}
    for row in trait_rows:
        if not isinstance(row, dict):
            continue
        slot = str(row.get("renderSlot", "")).strip().lower()
        value = str(row.get("sourceValue", "")).strip()
        if slot and value and slot not in trait_map:
            trait_map[slot] = value

    def trait_color(value, fallback):
        v = str(value or "").lower()
        colors = {
            "black": (0.025,0.025,0.03), "white": (0.88,0.86,0.81),
            "red": (0.72,0.035,0.045), "crimson": (0.52,0.015,0.055),
            "orange": (0.95,0.20,0.025), "gold": (0.95,0.58,0.08),
            "yellow": (0.95,0.78,0.06), "green": (0.06,0.42,0.18),
            "blue": (0.035,0.20,0.78), "navy": (0.025,0.06,0.20),
            "purple": (0.38,0.08,0.62), "pink": (0.90,0.20,0.48),
            "cyan": (0.03,0.72,0.78), "teal": (0.02,0.42,0.42),
            "silver": (0.62,0.67,0.72), "gray": (0.32,0.33,0.35),
            "grey": (0.32,0.33,0.35), "brown": (0.26,0.12,0.065),
            "tan": (0.62,0.43,0.27), "beige": (0.72,0.62,0.47),
            "blonde": (0.82,0.65,0.25), "blond": (0.82,0.65,0.25),
            "ginger": (0.62,0.20,0.055), "rainbow": (0.60,0.12,0.52)
        }
        for name, rgb in colors.items():
            if name in v:
                return rgb
        return fallback

    def tint(mat, rgb):
        mat.diffuse_color = (*rgb, 1.0)
        if mat.use_nodes:
            bsdf = mat.node_tree.nodes.get("Principled BSDF")
            if bsdf:
                bsdf.inputs["Base Color"].default_value = (*rgb, 1.0)

    # Trait colors should visibly influence the model rather than live only in metadata.
    for slot, target, fallback in [
        ("outfit", outfit, (0.20,0.20,0.22)),
        ("fur color", fur, (0.35,0.25,0.18)),
        ("skin color", fur, (0.48,0.34,0.28)),
        ("hair color", accent, (0.18,0.10,0.06)),
        ("eye color", accent, (0.18,0.45,0.70))
    ]:
        if slot in trait_map:
            tint(target, trait_color(trait_map[slot], fallback))

    # Distinct named accessory meshes are useful both visually and to the QA harness.
    headwear = trait_map.get("headwear", "").lower()
    if headwear and key != "fk":
        if any(word in headwear for word in ("crown", "tiara")):
            for side in (-1, 0, 1):
                cone("Trait_Crown_Peak_%s" % side, (side*0.105,0,head_y+0.245), 0.045, 0.008, 0.13, metal)
            cylinder("Trait_Crown_Band", (0,0,head_y+0.19), 0.205, 0.045, metal)
        elif any(word in headwear for word in ("helmet", "armor", "armour")):
            uv_sphere("Trait_Helmet_Shell", (0,0,head_y+0.075), (0.245,0.225,0.19), metal)
            cube("Trait_Helmet_Brow", (0,-0.20,head_y+0.025), (0.32,0.035,0.045), accent, 0.01)
        elif any(word in headwear for word in ("hat", "cap", "beanie", "top gear")):
            uv_sphere("Trait_Headwear_Crown", (0,0,head_y+0.19), (0.23,0.20,0.12), outfit)
            cube("Trait_Headwear_Brim", (0,-0.10,head_y+0.13), (0.32,0.27,0.045), outfit, 0.02)

    eyewear = trait_map.get("eye wear", "").lower()
    if eyewear:
        frame = metal if any(w in eyewear for w in ("gold", "silver", "metal")) else dark
        for side in (-1, 1):
            uv_sphere("Trait_Eyewear_Lens_%s" % side, (side*0.082,-0.216,head_y+0.035), (0.065,0.018,0.048), accent, 12, 8)
            cube("Trait_Eyewear_Frame_%s" % side, (side*0.082,-0.232,head_y+0.035), (0.135,0.018,0.018), frame, 0.006)
        cube("Trait_Eyewear_Bridge", (0,-0.235,head_y+0.035), (0.04,0.018,0.018), frame, 0.005)

    horns = trait_map.get("horns", "").lower()
    if horns:
        for side in (-1, 1):
            cone("Trait_Horn_%s" % side, (side*0.16,0,head_y+0.25), 0.07, 0.008, 0.25, accent, rotation=(0,side*0.25,side*0.12))

    if trait_map.get("wing"):
        for side in (-1, 1):
            uv_sphere("Trait_Wing_%s" % side, (side*0.37,0.10,1.32), (0.20,0.055,0.32), accent)
            for feather in range(3):
                cone("Trait_Wing_Feather_%s_%s" % (side,feather),
                     (side*(0.34+feather*0.065),0.08,1.16+feather*0.12),
                     0.045,0.006,0.20,light,rotation=(0,side*0.45,side*0.22))

    if trait_map.get("weapon"):
        weapon = trait_map["weapon"].lower()
        weapon_mat = metal if any(w in weapon for w in ("sword","blade","knife")) else dark
        cylinder("Trait_Weapon_Grip", (0.48,-0.08,0.80), 0.035, 0.22, dark, rotation=(0,0.1,0.15))
        if any(w in weapon for w in ("sword","blade","knife")):
            cone("Trait_Weapon_Blade", (0.48,-0.08,0.57), 0.075, 0.006, 0.42, weapon_mat, rotation=(0,0.1,0.15))
        elif any(w in weapon for w in ("gun","rifle","pistol","armed")):
            cube("Trait_Weapon_Firearm", (0.48,-0.08,0.69), (0.10,0.30,0.10), weapon_mat, 0.015)
            cylinder("Trait_Weapon_Barrel", (0.48,-0.24,0.69), 0.025, 0.18, metal, rotation=(1.5708,0,0))

    facial_hair = trait_map.get("facial hair", "").lower()
    if facial_hair and key != "racc":
        beard_scale = (0.12,0.055,0.12) if "stubble" in facial_hair else (0.14,0.07,0.19)
        uv_sphere("Trait_Facial_Hair", (0,-0.205,head_y-0.14), beard_scale, dark)

    tail = trait_map.get("tail", "").lower()
    if tail and key != "racc":
        tail_pts = [(0.15,0.12,0.78),(0.32,0.20,0.72),(0.48,0.21,0.84),(0.60,0.18,1.02)]
        make_curve("Trait_Tail", tail_pts, accent, 0.075)

    accessory = trait_map.get("accessory", "").lower()
    if accessory:
        if any(w in accessory for w in ("chain","necklace","jewel","pendant")):
            make_curve("Trait_Necklace",[(-0.16,-0.20,1.38),(-0.11,-0.235,1.22),(0,-0.245,1.17),(0.11,-0.235,1.22),(0.16,-0.20,1.38)],metal,0.014)
            uv_sphere("Trait_Pendant",(0,-0.255,1.16),(0.055,0.025,0.065),accent,12,8)
        elif any(w in accessory for w in ("backpack","pack")):
            cube("Trait_Backpack",(0,0.19,1.05),(0.28,0.18,0.32),outfit,0.025)
        elif any(w in accessory for w in ("shield","relic","totem")):
            cube("Trait_Relic",(0.40,-0.05,1.08),(0.18,0.07,0.24),metal,0.02)

    # Store normalized token traits as GLB metadata for QA. This does not make the asset
    # runtime-approved; visual likeness, rigging, rights and performance review remain required.
    # Generic accessory anchor and consistent metadata for downstream inspection.
    anchor = bpy.data.objects.new("NFT_Accessory_Anchor", None)
    bpy.context.collection.objects.link(anchor)
    anchor.location=(0,-0.25,1.35)
    anchor["collection_key"]=key
    anchor["token_id"]=str(spec["identity"].get("tokenId",""))
    anchor["blockout_only"]=True
    for obj in bpy.context.scene.objects:
        if obj.type == "MESH":
            obj["burncity_asset_stage"]="procedural-blockout"
            obj["source_token_id"]=str(spec["identity"].get("tokenId",""))
            obj["source_collection_key"]=key
    bpy.ops.object.select_all(action="SELECT")
    bpy.context.view_layer.objects.active=bpy.context.selected_objects[0] if bpy.context.selected_objects else None
    bpy.ops.export_scene.gltf(filepath=output_path, export_format="GLB", use_selection=False, export_apply=True)
    if not os.path.isfile(output_path) or os.path.getsize(output_path)<100:
        raise SystemExit("GLB export did not produce a usable output file")
    with open(output_path,"rb") as f: digest=hashlib.sha256(f.read()).hexdigest()
    print(json.dumps({"status":"blockout-generated","collectionKey":key,"tokenId":str(spec["identity"].get("tokenId","")),"output":output_path,"bytes":os.path.getsize(output_path),"sha256":digest,"runtimeApproved":False}))

if __name__ == "__main__":
    main()

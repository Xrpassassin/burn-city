const assert = require('node:assert/strict');
delete process.env.FLY_APP_NAME;
delete process.env.ZOMBIE_CLASSIC;
const Z = require('../server/cod');
const room = { ranked: false, daily: null, mapId: 'cosmodrome', zombies: new Map() };
Z.resetMap(room); Z.bind(room); room.power = 1;
const L = Z.layout(), p = { id: 1, x: L.forge.x, z: L.forge.z, y: 0, pts: 25000, guns: ['flamer'], slot: 0, perks: 0, up: [], up2: [], fuel: 10, cd: 1 };
const ev = [];
Z.use(room, p, ev);
assert.equal(p.pts, 20000, 'tier I costs 5000 points');
assert.deepEqual(p.up, ['flamer']);
assert.equal(ev.at(-1).tier, 1);
const tier1Damage = Z.wpn(p).dps;
Z.use(room, p, ev);
assert.equal(p.pts, 10000, 'tier II costs a further 10000 points');
assert.deepEqual(p.up2, ['flamer']);
assert.equal(ev.at(-1).tier, 2);
assert.ok(Z.wpn(p).dps > tier1Damage * 1.5, 'tier II materially increases damage');
assert.equal(Z.upBits(p), 5, 'snapshot upgrade bits distinguish tier II in the active slot');
Z.use(room, p, ev);
assert.equal(p.pts, 10000, 'a fully upgraded weapon cannot consume more points');
assert.equal(ev.at(-1).e, 'forge_have');
assert.equal(L.forge2Cost, 10000, 'client prompt uses the server-owned tier-II price');
console.log('Cosmodrome forge tiers passed: 9 assertions.');

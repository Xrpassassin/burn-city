const assert = require('node:assert/strict');
const { capture, restore } = require('../server/zombie-campaign');
const players = new Map([[7, { id: 7, pts: 12345, ptsAcc: 0.6, guns: ['flamer', 'beam'], slot: 1, perks: 17, up: ['beam'], up2: ['flamer'], bon: { dmg: 2, hp: 1 }, hp: 42, fuel: 12, down: 1, draft: [1] }]]);
const saved = capture(players);
players.get(7).pts = 500; players.get(7).guns = ['flamer']; players.get(7).perks = 0; players.get(7).up = []; players.get(7).up2 = []; players.get(7).bon = {};
restore(players, saved);
const p = players.get(7);
assert.equal(p.pts, 12345, 'points survive the map handoff');
assert.equal(p.ptsAcc, 0.6, 'fractional point accrual survives');
assert.deepEqual(p.guns, ['flamer', 'beam'], 'both weapon slots survive');
assert.equal(p.slot, 1, 'active weapon slot survives');
assert.equal(p.perks, 17, 'purchased perks survive');
assert.deepEqual(p.up, ['beam'], 'tier-I weapon upgrade survives');
assert.deepEqual(p.up2, ['flamer'], 'tier-II weapon upgrade survives');
assert.deepEqual(p.bon, { dmg: 2, hp: 1 }, 'between-wave boons survive');
assert.equal(p.hp, 270, 'max health is recalculated from preserved Juggernaut and health boon');
assert.equal(p.fuel, 100, 'fuel is refilled at arrival');
assert.equal(p.down, 0, 'downed state is cleared for the new map');
console.log('Zombie campaign carryover passed: 11 assertions.');

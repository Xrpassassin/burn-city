'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {inspectEstateLiabilityRows:inspect}=require('./estate-legacy-liability-inventory');
const db=new DatabaseSync(':memory:');
db.exec(`
CREATE TABLE estate_img_hourly_entitlements(owner TEXT,amount_units TEXT);
CREATE TABLE estate_hourly_payouts(id TEXT,state TEXT,img_units TEXT);
CREATE TABLE estate_payout_credits(owner TEXT,units TEXT);
CREATE TABLE estate_reward_carryovers(id TEXT,units TEXT);
CREATE TABLE estate_reward_xrp_credits(owner TEXT,drops TEXT);
CREATE TABLE estate_xrp_profit_payouts(id TEXT,state TEXT,amount_drops TEXT);
CREATE TABLE estate_xrp_profit_credits(owner TEXT,amount_drops TEXT);
INSERT INTO estate_img_hourly_entitlements VALUES('owner','50');
INSERT INTO estate_hourly_payouts VALUES('one','confirmed','15');
INSERT INTO estate_hourly_payouts VALUES('two','queued','20');
INSERT INTO estate_hourly_payouts VALUES('three','held','10');
INSERT INTO estate_payout_credits VALUES('owner','10');
INSERT INTO estate_reward_carryovers VALUES('three','10');
INSERT INTO estate_reward_xrp_credits VALUES('owner','12');
INSERT INTO estate_xrp_profit_payouts VALUES('four','queued','123');
INSERT INTO estate_xrp_profit_credits VALUES('owner','5');
`);
const a=inspect(db);
assert.equal(a.byTable.estate_img_hourly_entitlements.totalRecordedUnits,'50');
assert.equal(a.byTable.estate_hourly_payouts.totalRecordedUnits,'45');
assert.equal(a.byTable.estate_hourly_payouts.totalsByState.confirmed.recordedUnits,'15');
assert.equal(a.byTable.estate_hourly_payouts.totalsByState.queued.recordedUnits,'20');
assert.equal(a.byTable.estate_hourly_payouts.totalsByState.held.recordedUnits,'10');
assert.equal(a.byTable.estate_payout_credits.totalRecordedUnits,'10');
assert.equal(a.byTable.estate_reward_carryovers.totalRecordedUnits,'10');
assert.equal(a.byTable.estate_xrp_profit_payouts.totalsByState.queued.recordedUnits,'123');
assert.equal(a.byTable.estate_reward_xrp_credits.totalRecordedUnits,'12');
assert.equal(a.amountsMustNotBeAggregatedAcrossTables,true);
assert.equal(a.allPriorLiabilitiesEconomicallyReconciled,false);
assert.equal(a.purchaseActivationAuthorized,false);
assert.deepEqual(inspect(db),a);
db.exec("UPDATE estate_payout_credits SET units='-1'");
assert.throws(()=>inspect(db),/invalid_stored_liability_units/);
db.close();
const sparse=new DatabaseSync(':memory:');
assert.equal(inspect(sparse).byTable.estate_hourly_payouts.present,false);
assert.equal(inspect(sparse).byTable.estate_hourly_payouts.rows,null);
sparse.close();
console.log('Legacy reward liabilities: read-only independent units and overlap warnings passed');

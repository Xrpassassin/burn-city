'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateSaleReservations}=require('./estate-sale-reservations');
const {createEstateXamanPayloadStore}=require('./estate-sale-xaman-payload-store');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY)');
const reservations=createEstateSaleReservations(db),store=createEstateXamanPayloadStore(db);
const buyer='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',now=1000000;
reservations.reserve({reservationId:'reservation-00000001',propertyId:'trailer-01',buyer,now});
reservations.reserve({reservationId:'reservation-00000002',propertyId:'trailer-02',buyer,now});
const input={reservationId:'reservation-00000001',uuid:'uuid-1',buyer,now:now+1000};
assert.equal(store.bind(input).payload_uuid,'uuid-1');
assert.equal(store.bind(input).payload_uuid,'uuid-1');
assert.equal(store.get(input.reservationId).buyer,buyer);
assert.throws(()=>store.bind({...input,uuid:'uuid-2'}),/payload_binding_conflict/);
assert.throws(()=>store.bind({...input,reservationId:'reservation-00000002'}),/UNIQUE/);
assert.throws(()=>store.bind({...input,reservationId:'reservation-00000002',uuid:'uuid-3',now:now+900000}),/reservation_not_eligible_for_payload/);
console.log('Estate Xaman payload persistence tests passed');

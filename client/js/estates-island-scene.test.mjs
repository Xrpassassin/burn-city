import assert from 'node:assert/strict';
import {buildEstatesIslandScene,updateEstatesEntranceProximity} from './estates-island-scene.mjs';
const catalog={tiers:[{id:'trailer'},{id:'apartment'},{id:'starter'},{id:'family'},{id:'mansion'}],properties:Array.from({length:9},(_,i)=>({id:'property-'+(i+1),tier:['trailer','apartment','starter','family','mansion'][i%5],address:'Test address '+i}))};
const a=buildEstatesIslandScene({catalog,seed:123}),b=buildEstatesIslandScene({catalog,seed:123});
assert.equal(a.id,'estates-island');
assert.equal(a.status,'renderer-adapter-required');
assert.equal(a.topology.islandSurroundedByContinuousLake,true);
assert.equal(a.topology.waterCollision,true);
assert.equal(a.topology.swimmingEnabled,false);
assert.equal(a.access.find(x=>x.id==='island-gate').requiresExplicitConfirmation,true);
assert.equal(a.lots.length,21);
assert.equal(new Set(a.objects.map(x=>x.id)).size,a.objects.length);
assert.deepEqual(a.vegetation,b.vegetation,'seeded vegetation is deterministic');
assert.equal(a.lots.filter(x=>x.propertyId).length,9);
assert.equal(a.lots.filter(x=>!x.propertyId).length,12);
assert(a.lots.every(x=>Math.abs(x.position.x)<=105&&Math.abs(x.position.z)<=112));
assert(a.access.some(x=>x.kind==='bridge'&&x.vehicleAccess));
assert(a.access.some(x=>x.kind==='dock'&&x.boatsEnabled===false));
assert(a.roads.some(x=>x.orientation==='x')&&a.roads.some(x=>x.orientation==='z'));
assert.throws(()=>buildEstatesIslandScene({catalog,seed:1.5}),TypeError);
let shown=0,cancelled=0;
const adapter={showPrompt(){shown++;},cancelPrompt(){cancelled++;}};
assert.deepEqual(updateEstatesEntranceProximity({adapter,playerPosition:{x:0,y:0,z:132}}),{near:true,promptVisible:true,requiresConfirmation:true});
assert.equal(shown,1);
assert.equal(updateEstatesEntranceProximity({adapter,playerPosition:{x:50,y:0,z:132},wasPromptVisible:true}).promptVisible,false);
assert.equal(cancelled,1);
assert.throws(()=>updateEstatesEntranceProximity({adapter,playerPosition:{x:NaN,y:0,z:0}}),TypeError);
console.log('estates-island-scene: all tests passed');

'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateSaleReservations}=require('./estate-sale-reservations');
const {createEstateXamanPayloadStore}=require('./estate-sale-xaman-payload-store');
const {createEstateSaleSessionRecovery}=require('./estate-sale-session-recovery');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY)');
const reservations=createEstateSaleReservations(db);
const store=createEstateXamanPayloadStore(db);
const buyer='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',other='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd',now=1700000000000;
const r=reservations.reserve({reservationId:'reservation-00000001',propertyId:'trailer-01',buyer,now});
store.bind({reservationId:r.reservation_id,uuid:'payload-uuid-1',buyer,now:now+1000});
const recovery=createEstateSaleSessionRecovery(db);
assert.equal(recovery.get({reservationId:r.reservation_id,buyer,now:now+2000}).payloadUuid,'payload-uuid-1');
assert.equal(recovery.get({reservationId:r.reservation_id,buyer:other,now:now+2000}).error,'reservation_not_found');
const expired=recovery.get({reservationId:r.reservation_id,buyer,now:now+700000});
assert.equal(expired.status,'expired');assert.equal(expired.payloadUuid,null);
assert.equal(expired.salesEnabled,false);
console.log('Estate sale session recovery tests passed');

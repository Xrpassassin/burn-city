'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createImgHourlyRewardLedger}=require('./estate-img-hourly-rewards');
const {createImgHourlyBatchReconciler}=require('./estate-img-hourly-batches');
const db=new DatabaseSync(':memory:');
const treasury='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',source='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd';
const ledger=createImgHourlyRewardLedger(db,{treasury,imgIssuer:source,allowedSources:[source]});
const close=createImgHourlyBatchReconciler(db).close;
const hour=1700000000000-1700000000000%3600000;
const txHash='A'.repeat(64);
ledger.record({txHash,ledgerIndex:123,source,destination:treasury,issuer:source,amount:'1.000001',receivedAtMs:hour+1000,verified:true});
assert.throws(()=>close(hour,hour+3600000),/unallocated_or_inconsistent_receipts/);
assert.throws(()=>close(hour,hour+3599999),/hour_not_complete/);
ledger.allocate({txHash,holdings:[{propertyId:'trailer-01',acct:treasury},{propertyId:'trailer-02',acct:source}]});
const b=close(hour,hour+3600000);
assert.equal(b.totalUnits,'1000001');assert.equal(b.ownerCount,2);
assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_img_hourly_entitlements').get().n,2);
assert.equal(db.prepare('SELECT amount_units FROM estate_img_hourly_entitlements WHERE owner=?').get(treasury).amount_units,'500001');
assert.throws(()=>close(hour,hour+7200000),/hour_already_closed/);
assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_img_hourly_batches').get().n,1);
console.log('Atomic hourly IMG batch reconciliation and entitlement tests passed');

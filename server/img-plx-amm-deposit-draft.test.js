'use strict';
const assert=require('node:assert/strict');
const {POOL,TWO_ASSET,buildImgPlxDepositDraft}=require('./img-plx-amm-deposit-draft');
const acct='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb';
const img={currency:'IMG',issuer:acct};
const plx={currency:'PLX',issuer:'rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd'};
const input={account:acct,img,plx,imgAmount:'120.5',plxAmount:'3.75'};
const tx=buildImgPlxDepositDraft(input);
assert.equal(tx.TransactionType,'AMMDeposit');
assert.equal(tx.Flags,TWO_ASSET);
assert.equal(tx.Flags,1048576);
assert.deepEqual(tx.Amount,{...img,value:'120.5'});
assert.deepEqual(tx.Amount2,{...plx,value:'3.75'});
assert.equal(tx.Account,acct);
assert.equal(POOL,'rPDJ5BQxKQboHmaPEzy8n7D3RD5N7AwMiJ');
assert.equal(tx.Destination,undefined);
assert.equal(tx.TxnSignature,undefined);
assert.equal(tx.SigningPubKey,undefined);
assert.equal(tx.Fee,undefined);
for(const v of ['0','-1','1e9','NaN','0.0','1.'])assert.throws(()=>buildImgPlxDepositDraft({...input,imgAmount:v}),/invalid_positive_decimal/);
assert.throws(()=>buildImgPlxDepositDraft({...input,poolAddress:acct}),/unexpected_amm_pool/);
assert.throws(()=>buildImgPlxDepositDraft({...input,plx:img}),/identical_assets/);
assert.throws(()=>buildImgPlxDepositDraft({...input,img:{currency:'XRP'}}),/issued_asset_required/);
assert.throws(()=>buildImgPlxDepositDraft({...input,account:'invalid'}),/invalid_depositor/);
console.log('IMG/PLX unsigned double-sided AMM deposit draft tests passed');

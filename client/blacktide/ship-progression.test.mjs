import assert from 'node:assert/strict';
import { SHIP_CLASSES, createShip, shipStats, purchaseEquipment, purchaseUpgrade } from './ship-progression.js';
const sloop = createShip();
assert.equal(Object.keys(SHIP_CLASSES).length, 3);
assert.equal(shipStats(sloop).hull, 100);
sloop.currency = 500;
assert.equal(purchaseEquipment(sloop, 'heavy_cannon'), true);
assert.equal(purchaseEquipment(sloop, 'heavy_cannon'), true);
assert.equal(purchaseEquipment(sloop, 'heavy_cannon'), false, 'slot capacity enforced');
assert.equal(shipStats(sloop).damage, 40);
assert.equal(purchaseUpgrade(sloop, 'chainshot'), false, 'prerequisite required');
assert.equal(purchaseUpgrade(sloop, 'gun_drills'), true);
assert.equal(purchaseUpgrade(sloop, 'gun_drills'), false, 'upgrade is unique');
assert.equal(purchaseUpgrade(sloop, 'chainshot'), true);
assert.ok(shipStats(sloop).sailDamage > 0);
assert.equal(purchaseEquipment(sloop, '__proto__'), false);
assert.throws(() => createShip('unknown'));
const poor = createShip('frigate');
assert.equal(purchaseEquipment(poor, 'light_cannon'), false);
console.log('BlackTide ship progression tests passed');

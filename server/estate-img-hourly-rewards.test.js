'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createImgHourlyRewardLedger,units,epoch}=require('./estate-img-hourly-rewards');
const db=new DatabaseSync(':memory:');
const treasury='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',source='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd',issuer=source;
const ledger=createImgHourlyRewardLedger(db,{treasury,imgIssuer:issuer,allowedSources:[source]});
const receipt={txHash:'A'.repeat(64),ledgerIndex:123,source,destination:treasury,issuer,amount:'1.000001',receivedAtMs:1700000000000,verified:true};
assert.equal(ledger.record(receipt).inserted,true);
assert.equal(ledger.record(receipt).inserted,false);
assert.throws(()=>ledger.record({...receipt,amount:'2'}),/reward_hash_conflict/);
assert.throws(()=>ledger.record({...receipt,txHash:'B'.repeat(64),verified:false}),/unverified_reward_rejected/);
assert.throws(()=>ledger.record({...receipt,txHash:'B'.repeat(64),destination:source}),/ineligible_img_reward/);
assert.throws(()=>units('1.0000001'),/invalid_img_amount/);
assert.equal(epoch(1700000000000)%3600000,0);
const holdings=[{propertyId:'trailer-01',acct:treasury},{propertyId:'trailer-02',acct:source}];
const allocation=ledger.allocate({txHash:receipt.txHash,holdings});
assert.equal(allocation.allocations.reduce((s,r)=>s+BigInt(r.amountUnits),0n),1000001n);
assert.throws(()=>ledger.allocate({txHash:receipt.txHash,holdings}),/reward_already_allocated/);
assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_img_reward_receipts').get().n,1);
assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_img_hourly_allocations').get().n,2);
console.log('IMG reward receipt deduplication and hourly accounting tests passed; no payouts');

'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateSaleReservations}=require('./estate-sale-reservations');
const {createEstateXamanPayloadStore}=require('./estate-sale-xaman-payload-store');
const {createEstateLatePaymentReconciliation}=require('./estate-sale-late-reconciliation');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,acct TEXT NOT NULL,purchase_tx TEXT NOT NULL UNIQUE, purchase_amount_drops INTEGER NOT NULL,share_units INTEGER NOT NULL,purchased_at INTEGER NOT NULL)');
const buyer='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',treasury='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd',hash='C'.repeat(64),now=1700000000000;
const r=createEstateSaleReservations(db).reserve({reservationId:'reservation-00000001',propertyId:'trailer-01',buyer,now});
createEstateXamanPayloadStore(db).bind({reservationId:r.reservation_id,uuid:'late-uuid',buyer,now:now+1000});
let validated=false,lookups=0;
const sdk={payload:{create:async()=>{},get:async()=>({meta:{signed:true},response:{account:buyer,txid:hash}})}};
const client={request:async()=>{lookups++;return {result:{validated,ledger_index:101,tx_json:{hash,TransactionType:'Payment',Account:buyer,Destination:treasury,Amount:'3000000',Memos:[{Memo:{MemoType:Buffer.from('burncity/estates').toString('hex').toUpperCase(),MemoData:Buffer.from(r.reservation_id).toString('hex').toUpperCase()}}],date:Math.floor(now/1000)-946684800+10},meta:{TransactionResult:'tesSUCCESS',delivered_amount:'3000000'}}}}};
(async()=>{
 const disabled=createEstateLatePaymentReconciliation(db);
 assert.equal((await disabled.inspect({reservationId:r.reservation_id,buyer,now:r.expires_at+1000})).error,'estate_sales_disabled');
 const review=createEstateLatePaymentReconciliation(db,{sdk,client,treasury,enabled:true});
 assert.equal((await review.inspect({reservationId:r.reservation_id,buyer:treasury,now:r.expires_at+1000})).error,'reservation_not_found');
 assert.equal((await review.inspect({reservationId:r.reservation_id,buyer,now:r.expires_at-1000})).error,'reservation_not_expired');
 await assert.rejects(review.inspect({reservationId:r.reservation_id,buyer,now:r.expires_at+1000}),/payment_not_validated_success/);
 assert.equal(review.get(r.reservation_id),undefined);
 validated=true;
 const result=await review.inspect({reservationId:r.reservation_id,buyer,now:r.expires_at+1000});
 assert.equal(result.status,'needs_review');assert.equal(result.ownershipAssigned,false);
 assert.equal((await review.inspect({reservationId:r.reservation_id,buyer,now:r.expires_at+2000})).status,'needs_review');
 assert.equal(lookups,2);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_property_ownership').get().n,0);
 console.log('Estate late-payment reconciliation tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});

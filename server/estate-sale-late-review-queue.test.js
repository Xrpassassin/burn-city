'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateLatePaymentReconciliation}=require('./estate-sale-late-reconciliation');
const {createEstateLatePaymentReviewQueue}=require('./estate-sale-late-review-queue');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,acct TEXT NOT NULL,purchase_tx TEXT NOT NULL UNIQUE,purchase_amount_drops INTEGER NOT NULL,share_units INTEGER NOT NULL,purchased_at INTEGER NOT NULL)');
createEstateLatePaymentReconciliation(db);
const buyer='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb';
db.prepare("INSERT INTO estate_sale_reservations(reservation_id,property_id,buyer,price_drops,created_at,expires_at,status) VALUES(?,?,?,?,?,?,?)").run('reservation-00000001','trailer-01',buyer,3000000,1000,601000,'expired');
db.prepare("INSERT INTO estate_late_payment_reviews(reservation_id,buyer,tx_hash,observed_at) VALUES(?,?,?,?)").run('reservation-00000001',buyer,'A'.repeat(64),700000);
const queue=createEstateLatePaymentReviewQueue(db);
assert.equal(queue.list().length,1);
assert.equal(queue.list()[0].propertyId,'trailer-01');
assert.equal(queue.list()[0].priceDrops,3000000);
assert.equal(queue.list()[0].existingOwner,null);
assert.equal(queue.detail('reservation-00000001').manualReviewRequired,true);
assert.equal(queue.detail('reservation-00000001').ownershipAssignedByReview,false);
assert.equal(queue.detail('reservation-not-found'),null);
assert.throws(()=>queue.list({limit:1000}),/invalid_review_limit/);
assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_property_ownership').get().n,0);
console.log('Estate late-payment review queue tests passed');

'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {inspectEstateForwardRewardReadiness:read}=require('./estate-rlusd-forward-readiness');
const db=new DatabaseSync(':memory:');
const owner='rPDJ5BQxKQboHmaPEzy8n7D3RD5N7AwMiJ';
const other='r9DW7jqMXqa32TaTujSxdxcpwnPgJayG8V';
const none=read(db,{owner});
assert.equal(none.status,'forward_start_not_staged');
assert.equal(none.heldRealizationDraftCount,0);
assert.equal(none.ownerHeldDraftUnits,'0');
assert.equal(none.livePaymentsEnabled,false);
assert.equal(none.settlementEngineConnected,false);
assert.equal(none.verifiedRealizationIngestionConnected,false);
assert.equal(none.noGuaranteedHourlyPayment,true);
assert.equal(none.evaluationSchedule,'hourly');
assert.throws(()=>read(db,{owner:'bogus'}),/valid_owner_required/);
db.exec(`CREATE TABLE estate_rlusd_forward_reward_start(id INTEGER PRIMARY KEY,status TEXT);
INSERT INTO estate_rlusd_forward_reward_start VALUES(1,'staged');`);
const start=read(db);
assert.equal(start.forwardStartStaged,true);
assert.equal(start.status,'drafts_nonpaying');
assert.equal(start.livePaymentsEnabled,false);
db.exec(`CREATE TABLE estate_rlusd_forward_allocation_drafts(receipt_hash TEXT,drafted_units TEXT,state TEXT);
CREATE TABLE estate_rlusd_forward_owner_drafts(owner TEXT,amount_units TEXT,state TEXT);`);
const ins=db.prepare('INSERT INTO estate_rlusd_forward_allocation_drafts VALUES(?,?,?)');
const ownerIns=db.prepare('INSERT INTO estate_rlusd_forward_owner_drafts VALUES(?,?,?)');
ins.run('A'.repeat(64),'750','held');
ownerIns.run(owner,'500','held');ownerIns.run(other,'250','held');
const held=read(db,{owner});
assert.equal(held.heldRealizationDraftCount,1);
assert.equal(held.heldRealizationDraftUnits,'750');
assert.equal(held.ownerHeldDraftUnits,'500');
assert.equal(held.livePaymentsEnabled,false);
assert.equal(read(db,{owner:other}).ownerHeldDraftUnits,'250');
assert.equal(Object.hasOwn(read(db),'ownerHeldDraftUnits'),false);
ownerIns.run(other,'1','held');
assert.throws(()=>read(db),/forward_draft_ownership_unbalanced/);
db.prepare('DELETE FROM estate_rlusd_forward_owner_drafts WHERE owner=? AND amount_units=?').run(other,'1');
ins.run('B'.repeat(64),'bad','held');
assert.throws(()=>read(db),/invalid_forward_reward_reporting_units/);
db.prepare("DELETE FROM estate_rlusd_forward_allocation_drafts WHERE drafted_units='bad'").run();
db.prepare("UPDATE estate_rlusd_forward_allocation_drafts SET state='paid'").run();
assert.throws(()=>read(db),/unexpected_forward_draft_state/);
db.close();
console.log('IMG/RLUSD forward readiness: truthful nonpaying states, owner views, and fail-closed journals passed');

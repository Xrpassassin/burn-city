'use strict';
const assert=require('node:assert/strict');
const {handleEstateReviewRequest:handle}=require('./estate-sale-review-http');
const admin='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',stranger='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd';
let calls=0;
const queue={list:()=>{calls++;return [{reservation_id:'reservation-00000001'}]},detail:id=>{calls++;return id==='reservation-00000001'?{reservation_id:id}:null}};
const audit={history:()=>({ok:true,events:[]})};
const base={method:'GET',path:'/api/estates/admin/reviews',query:new URLSearchParams(),account:admin,adminTokenValid:true,allowedAccounts:new Set([admin]),queue,audit};
assert.equal(handle({...base,adminTokenValid:false}).code,403);
assert.equal(handle({...base,account:stranger}).code,403);
assert.equal(handle({...base,allowedAccounts:new Set()}).code,403);
assert.equal(calls,0,'unauthorized requests must not read queue');
assert.equal(handle(base).code,200);
assert.equal(handle({...base,method:'POST'}).code,405);
assert.equal(handle({...base,path:'/api/estates/admin/reviews/detail'}).code,404);
const detail=handle({...base,path:'/api/estates/admin/reviews/detail',query:new URLSearchParams('reservationId=reservation-00000001')});
assert.equal(detail.code,200);assert.equal(detail.body.readOnly,true);
assert.equal(handle({...base,path:'/api/estates/admin/reviews/unknown'}).code,404);
assert.equal(handle({...base,path:'/api/estates/admin/reviews/detail',query:new URLSearchParams('reservationId=reservation-00000001'),audit:{history:()=>({ok:false})}}).code,403);
console.log('Estates review HTTP handler tests passed');

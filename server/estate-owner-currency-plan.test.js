'use strict';
const assert = require('node:assert/strict');
const { planOwnerCurrencyPayouts } = require('./estate-owner-currency-plan');
const a = 'rGLEgQdktoN4Be5thhk6seg1HifGPBxY5Q';
const b = 'rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd';
const base = { epochId:'2026-10-28T18:00:00Z', distributableImgUnits:'1000000', holdings:[{propertyId:'trailer-01',acct:a},{propertyId:'trailer-02',acct:b}], fundingRef:'validated:funding:1', sourceLedgerIndex:1 };
const plan = planOwnerCurrencyPayouts({...base, preferences:{[a]:'IMG',[b]:'XRP'}});
assert.equal(plan.payouts.length,2);
assert.equal(plan.executionEnabled,false);
assert.equal(plan.payouts.reduce((n,p)=>n+BigInt(p.units),0n)+BigInt(plan.remainderUnits),1000000n);
const byWallet = Object.fromEntries(plan.payouts.map(p=>[p.wallet,p]));
assert.equal(byWallet[a].settlementMode,'direct_img');
assert.equal(byWallet[b].settlementMode,'swap_img_for_xrp');
assert.equal(byWallet[a].state,'held');
assert.equal(byWallet[b].state,'held');
assert.equal(byWallet[a].sourceCurrency,'IMG');
assert.equal(byWallet[b].sourceCurrency,'IMG');
assert.equal(planOwnerCurrencyPayouts({...base,preferences:{[a]:'IMG'}}).payouts.find(p=>p.wallet===b).settlementMode,'await_owner_selection');
assert.throws(()=>planOwnerCurrencyPayouts({...base,preferences:{[a]:'PLX'}}),/invalid_owner_payout_preference/);
assert.throws(()=>planOwnerCurrencyPayouts({...base,preferences:null}),/preferences_required/);
console.log('Owner currency planning tests passed');

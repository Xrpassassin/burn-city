#!/bin/bash
# Rebuild City citizen assets on the box (NOT in CI). Needs Blender 4.2 on PATH and SKETCHFAB_API_TOKEN in the env.
# The token is only sent as a request header; it is never printed, logged or written to disk.
#   scripts/city-citizens/build-all.sh            -> builds every "enabled": true model in models.json
#   scripts/city-citizens/build-all.sh trekker    -> one model (it must be enabled)
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$HERE/../.." && pwd)
SRC=${CITIZEN_SRC:-/workspace/npc-src}; OUT="$ROOT/client/assets/citizens"; QA=${CITIZEN_QA:-/workspace/qa/city-npcs/rig}
mkdir -p "$SRC" "$OUT"
[ -n "${SKETCHFAB_API_TOKEN:-}" ] || { echo "SKETCHFAB_API_TOKEN missing" >&2; exit 2; }
jq -c '.models[] | select(.enabled)' "$HERE/models.json" | while read -r m; do
  id=$(jq -r .id <<<"$m"); uid=$(jq -r .uid <<<"$m"); h=$(jq -r .height <<<"$m")
  [ $# -gt 0 ] && [ "$1" != "$id" ] && continue
  lic=$(curl -sf "https://api.sketchfab.com/v3/models/$uid" | jq -r .license.slug)
  [ "$lic" = by ] || { echo "$id: license '$lic' is not CC BY 4.0, refusing" >&2; exit 3; }
  if [ ! -f "$SRC/$id/scene.gltf" ]; then
    url=$(curl -sf -H "Authorization: Token $SKETCHFAB_API_TOKEN" "https://api.sketchfab.com/v3/models/$uid/download" | jq -r '.gltf.url // empty')
    [ -n "$url" ] || { echo "$id: no glTF download offered" >&2; exit 4; }
    curl -sf -o "$SRC/$id.zip" "$url"; mkdir -p "$SRC/$id"; (cd "$SRC/$id" && unzip -oq "../$id.zip")
  fi
  blender -b --factory-startup -P "$HERE/build_citizen.py" -- "$SRC/$id" "$id" "$h" "$OUT" "$QA" > "/tmp/citizen-$id.log" 2>&1 || true
  grep -q CITIZEN_DONE "/tmp/citizen-$id.log" && echo "$id: built" || { echo "$id: FAILED (see /tmp/citizen-$id.log)" >&2; FAILED=1; }
done
# 512 px copies of the near textures for phones (citizens.mjs swaps <id>-tex/ -> <id>-tex-512/ on mobile)
python3 - "$OUT" <<'PY'
import sys, glob, os
from PIL import Image
for d in glob.glob(os.path.join(sys.argv[1], '*-tex')):
    os.makedirs(d + '-512', exist_ok=True)
    for f in glob.glob(d + '/*.webp'):
        Image.open(f).resize((512, 512), Image.LANCZOS).save(os.path.join(d + '-512', os.path.basename(f)), 'WEBP', quality=80)
PY
# publish the runtime manifest (credits come from here too)
jq '{note:"Generated by scripts/city-citizens/build-all.sh. CC BY 4.0 models; credits in client/city-credits.html.", models:[.models[]|select(.enabled)|{id,title,artist,artistUrl,url,sex,height,license:"CC-BY-4.0"}]}' "$HERE/models.json" > "$OUT/models.json"
node "$HERE/write-credits.mjs"

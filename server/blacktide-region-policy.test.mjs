import assert from 'node:assert/strict';
import policy from './blacktide-region-policy.js';
const { REGIONS, canEnterRegion, enterRegion, setPvpOptIn, canPlayersFight } = policy;
const a={playerId:'a',regionId:'haven',instanceId:'1',safeHarbor:false,pvpEnabled:false};
const b={playerId:'b',regionId:'haven',instanceId:'1',safeHarbor:false,pvpEnabled:false};
assert.equal(setPvpOptIn(a,true,100000),false,'starter zone protected');
assert.equal(canPlayersFight(a,b),false);
assert.equal(canEnterRegion('emerald',[]),false);
assert.equal(enterRegion(a,'emerald','room1',['emerald']),true);
assert.equal(enterRegion(b,'emerald','room1',['emerald']),true);
assert.equal(a.pvpEnabled,false,'region transfer resets opt-in');
a.safeHarbor=false;b.safeHarbor=false;
assert.equal(setPvpOptIn(a,true,100000),true);
assert.equal(setPvpOptIn(b,true,100000),true);
assert.equal(canPlayersFight(a,b),true);
b.safeHarbor=true;assert.equal(canPlayersFight(a,b),false);
b.safeHarbor=false;b.instanceId='room2';assert.equal(canPlayersFight(a,b),false);
b.instanceId='room1';assert.equal(setPvpOptIn(a,false,100001),false,'toggle cooldown');
assert.equal(setPvpOptIn(a,false,160001),true);
assert.equal(canPlayersFight(a,b),false);
assert.equal(enterRegion(a,'invalid','room1',['invalid']),false);
assert.equal(enterRegion(a,'haven','../unsafe',[]),false);
assert.ok(REGIONS.shattered);
console.log('BlackTide region and PvP policy tests passed');

'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateSaleReservations}=require('./estate-sale-reservations');
const {createEstateXamanPayloadStore}=require('./estate-sale-xaman-payload-store');
const {createEstateSaleFinalization}=require('./estate-sale-finalization');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,acct TEXT NOT NULL,purchase_tx TEXT NOT NULL UNIQUE,purchase_amount_drops INTEGER NOT NULL,share_units INTEGER NOT NULL,purchased_at INTEGER NOT NULL)');
const buyer='rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',other='rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd',treasury=other,hash='A'.repeat(64),now=1700000000000;
const r=createEstateSaleReservations(db).reserve({reservationId:'reservation-00000001',propertyId:'trailer-01',buyer,now});
createEstateXamanPayloadStore(db).bind({reservationId:r.reservation_id,uuid:'uuid-1',buyer,now:now+1000});
let signed=false,validated=false;
const sdk={payload:{create:async()=>{throw Error('should_not_create')},get:async()=>({meta:{signed},response:{account:buyer,txid:hash}})}};
const client={request:async()=>({result:{validated,ledger_index:101,tx_json:{hash,TransactionType:'Payment',Account:buyer,Destination:treasury,Amount:'3000000',Memos:[{Memo:{MemoType:Buffer.from('burncity/estates').toString('hex').toUpperCase(),MemoData:Buffer.from(r.reservation_id).toString('hex').toUpperCase()}}],date:Math.floor(now/1000)-946684800+10},meta:{TransactionResult:'tesSUCCESS',delivered_amount:'3000000'}}})};
(async()=>{
 const disabled=createEstateSaleFinalization(db);
 assert.equal((await disabled.finalize({reservationId:r.reservation_id,buyer})).error,'estate_sales_disabled');
 const finalizer=createEstateSaleFinalization(db,{sdk,client,treasury,enabled:true});
 assert.equal((await finalizer.finalize({reservationId:r.reservation_id,buyer:other,now:now+20000})).error,'reservation_not_found');
 assert.equal((await finalizer.finalize({reservationId:r.reservation_id,buyer,now:now+20000})).error,'payment_not_signed_or_submitted');
 signed=true;
 await assert.rejects(finalizer.finalize({reservationId:r.reservation_id,buyer,now:now+20000}),/payment_not_validated_success/);
 assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_property_ownership').get().n,0);
 validated=true;
 assert.equal((await finalizer.finalize({reservationId:r.reservation_id,buyer,now:now+20000})).ownershipAssigned,true);
 assert.equal((await finalizer.finalize({reservationId:r.reservation_id,buyer,now:now+20000})).status,'already_settled');
 assert.equal(db.prepare('SELECT COUNT(*) n FROM estate_property_ownership').get().n,1);
 console.log('Estate Xaman verified finalization tests passed');
})().catch(e=>{console.error(e);process.exitCode=1});

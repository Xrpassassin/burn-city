'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateFreeStyleStore,ARCHITECTURES,PALETTES}=require('./estate-free-style');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,acct TEXT NOT NULL)');
db.prepare('INSERT INTO estate_property_ownership(property_id,acct) VALUES(?,?)').run('trailer-01','rOwner');
db.prepare('INSERT INTO estate_property_ownership(property_id,acct) VALUES(?,?)').run('mansion-01','rOwner');
let clock=1234;const store=createEstateFreeStyleStore({db,clock:()=>++clock});
assert.equal(ARCHITECTURES.length,3);
assert.equal(PALETTES.length,4);
assert.deepEqual(store.publicState().properties,[],'default finishes need not create public rows');
const initial=store.state({propertyId:'trailer-01',acct:'rOwner'});
assert.equal(initial.ok,true);assert.deepEqual(initial.style,{architecture:'classic',palette:'original'});assert.equal(initial.costXrp,0);
assert.equal(store.state({propertyId:'trailer-01',acct:'rGuest'}).error,'property_owner_required');
assert.equal(store.state({propertyId:'wrong',acct:'rOwner'}).error,'property_owner_required');
assert.equal(store.save({propertyId:'trailer-01',acct:'rGuest',architecture:'modern',palette:'forest'}).error,'property_owner_required');
assert.equal(store.save({propertyId:'trailer-01',acct:'rOwner',architecture:'script',palette:'forest'}).error,'invalid_free_style');
assert.equal(store.save({propertyId:'trailer-01',acct:'rOwner',architecture:'modern',palette:'infinite'}).error,'invalid_free_style');
assert.equal(store.publicState().properties.length,0,'invalid changes never reach public style feed');
const saved=store.save({propertyId:'trailer-01',acct:'rOwner',architecture:'modern',palette:'forest'});
assert.equal(saved.ok,true);assert.equal(saved.costXrp,0);assert.equal(saved.style.architecture,'modern');
assert.deepEqual(store.publicState().properties,[{propertyId:'trailer-01',architecture:'modern',palette:'forest'}]);
const restart=createEstateFreeStyleStore({db});assert.deepEqual(restart.state({propertyId:'trailer-01',acct:'rOwner'}).style,saved.style,'style persists across runtime restarts');
db.prepare('UPDATE estate_property_ownership SET acct=? WHERE property_id=?').run('rNewOwner','trailer-01');
assert.equal(restart.save({propertyId:'trailer-01',acct:'rOwner',architecture:'classic',palette:'original'}).error,'property_owner_required');
assert.deepEqual(restart.state({propertyId:'trailer-01',acct:'rNewOwner'}).style,saved.style,'free appearance transfers with property');
assert.equal(restart.save({propertyId:'trailer-01',acct:'rNewOwner',architecture:'rustic',palette:'coastal'}).ok,true);
assert.equal(restart.state({propertyId:'trailer-01',acct:'rNewOwner'}).style.architecture,'rustic');
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM estate_free_styles').get().n,1,'one immutable property row, updated without duplicated styles');
assert(!JSON.stringify(store.publicState()).includes('rOwner'),'public response cannot expose owner accounts');
db.close();
console.log('Estate free styles: ownership, validation, restart, public privacy, free changes and resale passed');

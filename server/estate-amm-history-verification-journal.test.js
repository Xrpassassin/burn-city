'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createAmmHistoryCheckpointStore}=require('./estate-amm-history-checkpoints');
const {createAmmHistoryVerificationJournal}=require('./estate-amm-history-verification-journal');
const db=new DatabaseSync(':memory:');
const store=createAmmHistoryCheckpointStore(db),journal=createAmmHistoryVerificationJournal(db);
const hash='A'.repeat(64),scanId='scan';
store.begin({scanId,treasury:'rwfnp2k2jU8VeFbkK85AJqu2NyAjtiaEpb',ledgerMin:100,ledgerMax:200});
store.recordPage({scanId,expectedPageCount:0,transactions:[{hash,ledgerIndex:101,validated:true,transactionType:'AMMDeposit'}],nextMarker:null});
const evidence={storedHashVerified:true,storedLedgerVerified:true,distributable:false,imgDelta:'-10',plxDelta:'-20'};
const data={scanId,hash,ledgerIndex:101,status:'verified_structure',evidence};
assert.equal(journal.record(data).distributable,0);
assert.equal(journal.record(data).status,'verified_structure');
assert.throws(()=>journal.record({...data,evidence:{...evidence,imgDelta:'100'}}),/verification_conflict/);
assert.throws(()=>journal.record({...data,ledgerIndex:102}),/stored_transaction_mismatch/);
assert.throws(()=>journal.record({...data,hash:'B'.repeat(64)}),/stored_transaction_mismatch/);
assert.throws(()=>journal.record({...data,evidence:{...evidence,distributable:true}}),/unsafe_or_incomplete_verification_evidence/);
console.log('AMM verification journal tests passed');

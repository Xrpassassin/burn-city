'use strict';
const assert = require('node:assert/strict');
const { DatabaseSync } = require('node:sqlite');
const { createOwnerEpochStore } = require('./estate-owner-epoch-store');
const a = 'rGLEgQdktoN4Be5thhk6seg1HifGPBxY5Q';
const b = 'rsJJMwweNS6GveA12RV7xmGNG1HdgAuiNd';
const db = new DatabaseSync(':memory:');
const store = createOwnerEpochStore(db);
const base = { epochId:'2026-10-28T18:00:00Z', distributableImgUnits:'1000000', holdings:[{propertyId:'trailer-01',acct:a},{propertyId:'trailer-02',acct:b}], fundingRef:'verified:ledger:100', sourceLedgerIndex:100, preferences:{[a]:'IMG',[b]:'XRP'} };
const first = store.create(base);
assert.equal(first.payouts.length,2);
assert.equal(first.payouts.reduce((sum,p)=>sum+BigInt(p.img_units),0n)+BigInt(first.epoch.remainder_units),1000000n);
assert.equal(first.payouts.find(p=>p.wallet===a).settlement_currency,'IMG');
assert.equal(first.payouts.find(p=>p.wallet===b).settlement_currency,'XRP');
assert.throws(()=>store.create({...base,preferences:{[a]:'XRP',[b]:'IMG'}}),/epoch_already_frozen/);
assert.equal(store.get(base.epochId).payouts.find(p=>p.wallet===a).settlement_currency,'IMG');
assert.throws(()=>store.create({...base,epochId:'2026-10-28T19:00:00Z'}),/UNIQUE constraint failed/);
assert.equal(store.get('2026-10-28T19:00:00Z'),null);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM estate_img_reward_intents').get().n,2);
console.log('Durable owner epoch tests passed');

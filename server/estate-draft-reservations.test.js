'use strict';
const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createEstateReservations}=require('./estate-draft-reservations');
const db=new DatabaseSync(':memory:');
db.exec('CREATE TABLE estate_property_ownership(property_id TEXT PRIMARY KEY,owner_acct TEXT NOT NULL)');
let clock=1000000;
const reservations=createEstateReservations(db,{now:()=>clock});
const wallet='rWalletA',other='rWalletB';
const r=reservations.reserve({wallet,propertyId:'trailer-01',intentId:'i1',ttlMs:1000});
assert.equal(r.ok,true);assert.equal(r.priceDrops,3000000);
assert.deepEqual(reservations.reserve({wallet:other,propertyId:'trailer-01',intentId:'i2'}),{ok:false,reason:'unavailable'});
assert.throws(()=>reservations.reserve({wallet,propertyId:'trailer-02',intentId:'i1'}),/UNIQUE/);
assert.equal(reservations.cancel({wallet:other,intentId:'i1'}),false);
assert.equal(reservations.cancel({wallet,intentId:'i1'}),true);
assert.equal(reservations.reserve({wallet:other,propertyId:'trailer-01',intentId:'i3'}).ok,true);
clock+=300001;
assert.equal(reservations.reserve({wallet,propertyId:'trailer-01',intentId:'i4'}).ok,true);
for(const [index,id] of ['trailer-02','trailer-03','trailer-04'].entries())assert.equal(reservations.reserve({wallet,propertyId:id,intentId:'t'+index}).ok,true);
db.prepare('INSERT INTO estate_property_ownership(property_id,owner_acct) VALUES(?,?)').run('trailer-01','rAlreadyOwned');
assert.deepEqual(reservations.reserve({wallet:other,propertyId:'trailer-01',intentId:'taken'}),{ok:false,reason:'unavailable'});
// Five-per-tier cap must count both owned property and pending reservations.
db.prepare('INSERT INTO estate_property_ownership(property_id,owner_acct) VALUES(?,?)').run('starter-01',wallet);
for(const [index,id] of ['starter-02','starter-03','starter-04','cabin-01'].entries())assert.equal(reservations.reserve({wallet,propertyId:id,intentId:'s'+index}).ok,true);
assert.deepEqual(reservations.reserve({wallet,propertyId:'cabin-02',intentId:'overcap'}),{ok:false,reason:'tier_cap'});
assert.equal(db.prepare("SELECT COUNT(*) AS n FROM estate_draft_reservations WHERE id='overcap'").get().n,0);
assert.equal(reservations.reserve({wallet:other,propertyId:'cabin-02',intentId:'otherbuyer'}).ok,true);
assert.deepEqual(reservations.reserve({wallet,propertyId:'missing',intentId:'missing'}),{ok:false,reason:'unknown_property'});
assert.throws(()=>reservations.reserve({wallet,propertyId:'family-01',intentId:'bad',ttlMs:0}),/invalid_ttl/);
assert.equal(db.prepare('SELECT COUNT(*) AS n FROM estate_property_ownership').get().n,2,'reservations never create ownership');
db.close();
console.log('Estate draft reservation tests passed');

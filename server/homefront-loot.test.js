'use strict';
const assert=require('node:assert/strict');
const Loot=require('./homefront-loot');
const Inventory=require('./homefront-inventory');
const W=require('./homefront-world');
let world=W.defaultWorld();
const entered=W.enter(world,'loot-tester',1000);world=entered.world;
const node=Loot.NODES.find(n=>n.id==='loot_bus_depot');
world.players['loot-tester'].x=node.x;world.players['loot-tester'].z=node.z;
let result=Loot.claim(world.lootNodes,{account:'loot-tester',player:world.players['loot-tester'],nodeId:node.id,now:2000,addItem:(bag,id,amount)=>Inventory.add(bag,id,amount)});
world.lootNodes=result.state;
assert.equal(result.node.id,node.id);
assert.ok(result.accepted.length>0,'valid pickup grants at least one carried item');
assert.ok(result.accepted.every(d=>Inventory.ITEMS[d.item]),'all server rolls use registered item IDs');
assert.ok(world.players['loot-tester'].inventory && Object.values(world.players['loot-tester'].inventory).some(n=>n>0),'loot updates the carried pack');
assert.ok(world.lootNodes[node.id].readyAt>2000,'claim persists a shared node cooldown');
assert.throws(()=>Loot.claim(world.lootNodes,{account:'loot-tester',player:world.players['loot-tester'],nodeId:node.id,now:3000,addItem:(bag,id,amount)=>Inventory.add(bag,id,amount)}),/loot_node_empty/);
assert.throws(()=>Loot.claim(world.lootNodes,{account:'loot-tester',player:{x:100,z:100,inventory:{}},nodeId:node.id,now:4000,addItem:(bag,id,amount)=>Inventory.add(bag,id,amount)}),/too_far_from_loot/);
assert.throws(()=>Loot.claim(world.lootNodes,{account:'loot-tester',player:world.players['loot-tester'],nodeId:'bad-node',now:4000,addItem:(bag,id,amount)=>Inventory.add(bag,id,amount)}),/unknown_loot_node/);
const packed=Loot.claim({}, {account:'full-pack',player:{x:node.x,z:node.z,inventory:{food:8,water:8,meds:5,ammo:12,scrap:8,wood:8}},nodeId:node.id,now:5000,addItem:(bag,id,amount)=>Inventory.add(bag,id,amount)});
assert.ok(packed.overflow.length>0,'full packs report overflow rather than creating hidden inventory');
const migrated=Loot.normalize({loot_bus_depot:{readyAt:'bad',claimedBy:{}}});
assert.equal(migrated.loot_bus_depot.readyAt,0,'malformed legacy node state safely migrates');
assert.equal(migrated.loot_bus_depot.claimedBy,null);
console.log('Homefront physical loot node tests passed.');
